using System; // A instrução "using" importa a biblioteca necessária para usar o Console.

class Program // Definimos uma classe chamada "Program". Em C#, a execução do código sempre começa na classe 'Program'.
{
    static void Main() // O método "Main" é o ponto de entrada do programa, é aqui que o programa começa a execução.
    {
        Console.WriteLine("Olá, Mundo!"); // Exibe a mensagem "Olá, Mundo!" no terminal.
        Console.ReadLine(); // Aguarda o usuário pressionar Enter antes de fechar o terminal.
    }
}

